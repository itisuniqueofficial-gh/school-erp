<?php

declare(strict_types=1);

namespace Core\Database\Schema;

/**
 * Translates the project's MySQL-flavoured migration SQL into PostgreSQL DDL.
 *
 * Scope: exactly the constructs the migrations use (CREATE TABLE with ENUM,
 * KEY/UNIQUE KEY, generated columns, FKs; ALTER TABLE ADD/MODIFY/CHANGE/DROP
 * INDEX/ADD KEY; CREATE [UNIQUE] INDEX; INSERT IGNORE). Anything it does not
 * recognise is passed through unchanged, so an unsupported construct fails
 * loudly on the server instead of being silently dropped.
 *
 * Type mapping (all integers become signed; the app never needs the unsigned range):
 *   TINYINT/SMALLINT/YEAR -> SMALLINT (INT/SMALLINT UNSIGNED widen one step), INT/BIGINT -> BIGINT,
 *   AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY, DATETIME -> TIMESTAMP(0),
 *   ENUM(...) -> VARCHAR + CHECK, LONGTEXT/MEDIUMTEXT -> TEXT, DOUBLE -> DOUBLE PRECISION,
 *   VIRTUAL generated columns -> STORED.
 * Boolean-like TINYINT(1) stays a SMALLINT holding 0/1 so application code is unchanged.
 */
final class PostgresTranslator
{
    /**
     * Deterministic PostgreSQL index name. Index names are schema-wide in
     * PostgreSQL (per-table in MySQL), so they are prefixed with the table.
     */
    public static function indexName(string $table, string $name): string
    {
        $n = str_starts_with($name, $table . '_') ? $name : $table . '_' . $name;
        return strlen($n) <= 63 ? $n : substr($n, 0, 54) . '_' . substr(md5($n), 0, 8);
    }

    /** @return string[] one or more PostgreSQL statements for one MySQL statement */
    public function translate(string $sql): array
    {
        // Trailing `-- comment` text may contain commas/quotes that would confuse the column splitter.
        $sql = trim(\Core\Database\Dialect::stripComments($sql));
        if ($sql === '') {
            return [];
        }
        if (preg_match('/^SET\s+FOREIGN_KEY_CHECKS/i', $sql) === 1) {
            return [];
        }
        if (preg_match('/^CREATE\s+TABLE/i', $sql) === 1) {
            return $this->createTable($sql);
        }
        if (preg_match('/^ALTER\s+TABLE/i', $sql) === 1) {
            return $this->alterTable($sql);
        }
        if (preg_match('/^CREATE\s+(UNIQUE\s+)?INDEX/i', $sql) === 1) {
            return [$this->createIndex($sql)];
        }
        if (preg_match('/^DROP\s+INDEX\s+`?(\w+)`?\s+ON\s+`?(\w+)`?/i', $sql, $m) === 1) {
            return ['DROP INDEX IF EXISTS "' . self::indexName($m[2], $m[1]) . '"'];
        }
        if (preg_match('/^INSERT\s+IGNORE\s+INTO/i', $sql) === 1) {
            return [$this->plain(preg_replace('/^INSERT\s+IGNORE\s+INTO/i', 'INSERT INTO', $sql) . ' ON CONFLICT DO NOTHING')];
        }
        if (preg_match('/^(INSERT|UPDATE|DELETE|SELECT)\b/i', $sql) === 1) {
            return [$this->plain($sql)];
        }
        return [$this->plain($sql)];
    }

    // ------------------------------------------------------------------ CREATE TABLE

    /** @return string[] */
    private function createTable(string $sql): array
    {
        if (preg_match('/^CREATE\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?\s*\((.*)\)\s*[^()]*$/is', $sql, $m) !== 1) {
            return [$this->plain($sql)];
        }
        $table = $m[2];
        $cols = [];
        $post = [];
        foreach ($this->splitTop($m[3]) as $def) {
            $def = trim($def);
            if ($def === '') {
                continue;
            }
            if (preg_match('/^(UNIQUE\s+)?(KEY|INDEX)\s+`?(\w+)`?\s*\((.+)\)$/is', $def, $k) === 1) {
                $post[] = sprintf('CREATE %sINDEX IF NOT EXISTS "%s" ON "%s" (%s)', $k[1] !== '' ? 'UNIQUE ' : '',
                    self::indexName($table, $k[3]), $table, $this->indexCols($k[4]));
            } elseif (preg_match('/^UNIQUE\s+`?(\w+)`?\s*\((.+)\)$/is', $def, $k) === 1) {
                $post[] = sprintf('CREATE UNIQUE INDEX IF NOT EXISTS "%s" ON "%s" (%s)', self::indexName($table, $k[1]), $table, $this->indexCols($k[2]));
            } elseif (preg_match('/^PRIMARY\s+KEY\s*\((.+)\)$/is', $def, $k) === 1) {
                $cols[] = 'PRIMARY KEY (' . $this->indexCols($k[1]) . ')';
            } elseif (preg_match('/^CONSTRAINT\s+`?(\w+)`?\s+FOREIGN\s+KEY/i', $def) === 1) {
                $cols[] = $this->quoteIdents($def);
            } else {
                $cols[] = $this->columnDef($def);
            }
        }
        $out = ['CREATE TABLE IF NOT EXISTS "' . $table . '" (' . "\n    " . implode(",\n    ", $cols) . "\n)"];
        return array_merge($out, $post);
    }

    private function columnDef(string $def): string
    {
        if (preg_match('/^`?(\w+)`?\s+(.*)$/s', $def, $m) !== 1) {
            return $def;
        }
        $name = $m[1];
        $rest = $m[2];
        $check = '';

        // ENUM('a','b') -> VARCHAR(n) + CHECK
        if (preg_match('/^ENUM\s*\(((?:\'(?:[^\']|\'\')*\'\s*,?\s*)+)\)/i', $rest, $e) === 1) {
            preg_match_all("/'((?:[^']|'')*)'/", $e[1], $vals);
            $len = max(array_map('strlen', $vals[1])) ?: 1;
            $quoted = implode(',', array_map(static fn ($v) => "'" . $v . "'", $vals[1]));
            $rest = 'VARCHAR(' . max($len, 20) . ')' . substr($rest, strlen($e[0]));
            $check = ' CHECK ("' . $name . '" IN (' . $quoted . '))';
        }

        $auto = preg_match('/\bAUTO_INCREMENT\b/i', $rest) === 1;
        $rest = preg_replace('/\s+(CHARACTER\s+SET|CHARSET)\s+\w+/i', '', $rest) ?? $rest;
        $rest = preg_replace('/\s+COLLATE\s+\w+/i', '', $rest) ?? $rest;
        $rest = preg_replace("/\\s+COMMENT\\s+'(?:[^']|'')*'/i", '', $rest) ?? $rest;
        $rest = preg_replace('/\s+AUTO_INCREMENT\b/i', '', $rest) ?? $rest;
        $rest = $this->mapType($rest);
        $rest = preg_replace('/\bVIRTUAL\b/i', 'STORED', $rest) ?? $rest;
        $rest = $this->quoteIdents($rest);

        if ($auto) {
            // identity replaces NOT NULL / DEFAULT
            $rest = preg_replace('/\s+(NOT\s+NULL|NULL)\b/i', '', $rest) ?? $rest;
            $rest = preg_replace('/\s+DEFAULT\s+\S+/i', '', $rest) ?? $rest;
            $rest = trim($rest) . ' GENERATED BY DEFAULT AS IDENTITY';
        }
        return '"' . $name . '" ' . trim($rest) . $check;
    }

    private function mapType(string $s): string
    {
        // Order matters: most specific first.
        $map = [
            '/^(TINYINT|SMALLINT)(\(\d+\))?\s+UNSIGNED\b/i' => 'INTEGER',
            '/^(TINYINT|SMALLINT|YEAR)(\(\d+\))?/i'         => 'SMALLINT',
            '/^(MEDIUMINT|INT|INTEGER)(\(\d+\))?(\s+UNSIGNED)?\b/i' => 'BIGINT',
            '/^BIGINT(\(\d+\))?(\s+UNSIGNED)?\b/i'          => 'BIGINT',
            '/^DATETIME(\(\d+\))?/i'                        => 'TIMESTAMP(0)',
            '/^(LONGTEXT|MEDIUMTEXT|TINYTEXT)\b/i'          => 'TEXT',
            '/^(LONGBLOB|MEDIUMBLOB|BLOB|TINYBLOB)\b/i'     => 'BYTEA',
            '/^DOUBLE\b(\s+PRECISION)?/i'                   => 'DOUBLE PRECISION',
            '/^DECIMAL(\(\d+\s*,\s*\d+\))?(\s+UNSIGNED)?/i'  => 'NUMERIC$1',
            '/^FLOAT(\(\d+(,\s*\d+)?\))?(\s+UNSIGNED)?/i'    => 'REAL',
        ];
        foreach ($map as $re => $to) {
            if (preg_match($re, $s) === 1) {
                $s = preg_replace($re, $to, $s, 1) ?? $s;
                break;
            }
        }
        // Generated column / any remaining standalone UNSIGNED.
        return preg_replace('/\s+UNSIGNED\b/i', '', $s) ?? $s;
    }

    // ------------------------------------------------------------------ ALTER TABLE

    /** @return string[] */
    private function alterTable(string $sql): array
    {
        if (preg_match('/^ALTER\s+TABLE\s+`?(\w+)`?\s+(.*)$/is', $sql, $m) !== 1) {
            return [$this->plain($sql)];
        }
        $table = $m[1];
        $out = [];
        $alter = [];
        foreach ($this->splitTop($m[2]) as $act) {
            $act = trim($act);
            if (preg_match('/^ADD\s+(.+)$/is', $act, $add) === 1) {
                $body = trim($add[1]);
                if (preg_match('/^(UNIQUE\s+)?(?:KEY|INDEX)\s+`?(\w+)`?\s*\((.+)\)$/is', $body, $k) === 1
                    || preg_match('/^(UNIQUE)\s+`?(\w+)`?\s*\((.+)\)$/is', $body, $k) === 1) {
                    $out[] = sprintf('CREATE %sINDEX IF NOT EXISTS "%s" ON "%s" (%s)', $k[1] !== '' ? 'UNIQUE ' : '',
                        self::indexName($table, $k[2]), $table, $this->indexCols($k[3]));
                } elseif (preg_match('/^(CONSTRAINT|FOREIGN\s+KEY|PRIMARY\s+KEY)\b/i', $body) === 1) {
                    $alter[] = 'ADD ' . $this->quoteIdents($body);
                } else {
                    $def = preg_replace('/^COLUMN\s+/i', '', $body) ?? $body;
                    $def = preg_replace('/\s+(AFTER\s+`?\w+`?|FIRST)\s*$/i', '', $def) ?? $def;
                    $alter[] = 'ADD COLUMN IF NOT EXISTS ' . $this->columnDef($def);
                }
            } elseif (preg_match('/^DROP\s+(INDEX|KEY)\s+`?(\w+)`?$/i', $act, $k) === 1) {
                $out[] = 'DROP INDEX IF EXISTS "' . self::indexName($table, $k[2]) . '"';
            } elseif (preg_match('/^DROP\s+FOREIGN\s+KEY\s+`?(\w+)`?$/i', $act, $k) === 1) {
                $alter[] = 'DROP CONSTRAINT IF EXISTS "' . $k[1] . '"';
            } elseif (preg_match('/^DROP\s+(?:COLUMN\s+)?`?(\w+)`?$/i', $act, $k) === 1) {
                $alter[] = 'DROP COLUMN IF EXISTS "' . $k[1] . '"';
            } elseif (preg_match('/^MODIFY\s+(?:COLUMN\s+)?`?(\w+)`?\s+(.+)$/is', $act, $k) === 1) {
                array_push($alter, ...$this->modify($k[1], $k[2]));
            } elseif (preg_match('/^CHANGE\s+(?:COLUMN\s+)?`?(\w+)`?\s+`?(\w+)`?\s+(.+)$/is', $act, $k) === 1) {
                if ($k[1] !== $k[2]) {
                    $out[] = sprintf('ALTER TABLE "%s" RENAME COLUMN "%s" TO "%s"', $table, $k[1], $k[2]);
                }
                array_push($alter, ...$this->modify($k[2], $k[3]));
            } else {
                $alter[] = $this->quoteIdents($act);
            }
        }
        if ($alter !== []) {
            array_unshift($out, 'ALTER TABLE "' . $table . '" ' . implode(', ', $alter));
        }
        return $out;
    }

    /** @return string[] */
    private function modify(string $col, string $def): array
    {
        $null = null;
        if (preg_match('/\bNOT\s+NULL\b/i', $def) === 1) {
            $null = false;
            $def = preg_replace('/\s*\bNOT\s+NULL\b/i', '', $def) ?? $def;
        } elseif (preg_match('/\bNULL\b/i', $def) === 1) {
            $null = true;
            $def = preg_replace('/\s*\bNULL\b/i', '', $def) ?? $def;
        }
        $default = null;
        if (preg_match('/\s+DEFAULT\s+(\S+)/i', $def, $d) === 1) {
            $default = $d[1];
            $def = preg_replace('/\s+DEFAULT\s+\S+/i', '', $def) ?? $def;
        }
        $def = preg_replace('/\s+(AFTER|FIRST)\s*`?\w*`?\s*$/i', '', $def) ?? $def;
        $type = trim($this->mapType(trim($def)));
        $out = ['ALTER COLUMN "' . $col . '" TYPE ' . $type];
        if ($null !== null) {
            $out[] = 'ALTER COLUMN "' . $col . '" ' . ($null ? 'DROP' : 'SET') . ' NOT NULL';
        }
        if ($default !== null) {
            $out[] = 'ALTER COLUMN "' . $col . '" SET DEFAULT ' . $default;
        }
        return $out;
    }

    private function createIndex(string $sql): string
    {
        if (preg_match('/^CREATE\s+(UNIQUE\s+)?INDEX\s+`?(\w+)`?\s+ON\s+`?(\w+)`?\s*\((.+)\)\s*$/is', $sql, $m) !== 1) {
            return $this->plain($sql);
        }
        return sprintf('CREATE %sINDEX IF NOT EXISTS "%s" ON "%s" (%s)', $m[1] !== '' ? 'UNIQUE ' : '', self::indexName($m[3], $m[2]), $m[3], $this->indexCols($m[4]));
    }

    // ------------------------------------------------------------------ helpers

    /** Strip MySQL prefix lengths and quote identifiers: `title`(191) -> "title". */
    private function indexCols(string $cols): string
    {
        $cols = preg_replace('/`?(\w+)`?\s*\(\d+\)/', '$1', $cols) ?? $cols;
        return implode(', ', array_map(static fn ($c) => '"' . trim($c, " `\"") . '"', explode(',', $cols)));
    }

    /** Backticks -> double quotes, outside string literals. */
    private function quoteIdents(string $sql): string
    {
        return $this->mapOutsideStrings($sql, static fn (string $chunk): string => str_replace('`', '"', $chunk));
    }

    private function plain(string $sql): string
    {
        $sql = $this->quoteIdents($sql);
        return (new \Core\Database\Dialect('pgsql'))->translate($sql);
    }

    /** @return string[] top-level comma-separated parts (parentheses and quotes respected) */
    private function splitTop(string $s): array
    {
        $parts = [];
        $depth = 0;
        $cur = '';
        $q = null;
        $len = strlen($s);
        for ($i = 0; $i < $len; $i++) {
            $c = $s[$i];
            if ($q !== null) {
                $cur .= $c;
                if ($c === $q) {
                    if (($s[$i + 1] ?? '') === $q) {
                        $cur .= $s[++$i];
                    } else {
                        $q = null;
                    }
                }
                continue;
            }
            if ($c === "'" || $c === '"' || $c === '`') {
                $q = $c;
                $cur .= $c;
            } elseif ($c === '(') {
                $depth++;
                $cur .= $c;
            } elseif ($c === ')') {
                $depth--;
                $cur .= $c;
            } elseif ($c === ',' && $depth === 0) {
                $parts[] = $cur;
                $cur = '';
            } else {
                $cur .= $c;
            }
        }
        if (trim($cur) !== '') {
            $parts[] = $cur;
        }
        return $parts;
    }

    private function mapOutsideStrings(string $sql, callable $fn): string
    {
        return \Core\Database\Dialect::mapOutsideStrings($sql, $fn);
    }
}
